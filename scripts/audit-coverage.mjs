// NANO-10 coverage audit: every requirement ID in Requirements.md is traced in REQUIREMENTS_TRACEABILITY.md, and every
// route in the handover route map has a screen file (or is a documented web/dialog route). Prints a Markdown report;
// exits 1 when something is untraced or missing, so CI can keep it honest.
//   node scripts/audit-coverage.mjs > docs/release/coverage.md
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const read = (p) => readFileSync(join(root, p), 'utf8');

// ---------- requirements ----------
const reqText = read('Requirements.md');
const ids = [...new Set([...reqText.matchAll(/^\|\s*([A-Z]{2,6} \d{2})\s*\|\s*(Must|Should|Could|Backlog|Won't)?/gm)].map((m) => m[1]))];
const priority = Object.fromEntries([...reqText.matchAll(/^\|\s*([A-Z]{2,6} \d{2})\s*\|\s*([A-Za-z' ]+?)\s*\|/gm)].map((m) => [m[1], m[2].trim()]));

const trace = read('REQUIREMENTS_TRACEABILITY.md');
const traced = new Set();
for (const line of trace.split('\n').filter((l) => l.startsWith('|'))) {
  const cell = line.split('|')[1] ?? '';
  // "PROMO 02–05, 09, 11", "NOTIF 01 / NOTIF 06", "WALT 15", "AUTH 03 / AUT-08"
  for (const m of cell.matchAll(/([A-Z]{2,6}) ((?:\d{2}(?:\s*[–-]\s*\d{2})?(?:,\s*)?)+)/g)) {
    const prefix = m[1];
    for (const part of m[2].split(',').map((s) => s.trim()).filter(Boolean)) {
      const [a, b] = part.split(/\s*[–-]\s*/).map(Number);
      for (let n = a; n <= (b ?? a); n++) traced.add(`${prefix} ${String(n).padStart(2, '0')}`);
    }
  }
}
const untraced = ids.filter((id) => !traced.has(id));

// ---------- routes ----------
const routes = JSON.parse(read('apps/mobile/src/navigation/routes.json'));
const appDir = 'apps/mobile/src/app';
const fileFor = (route) => {
  const base = join(appDir, route === '/' ? 'index' : route);
  return [`${base}.tsx`, join(base, 'index.tsx')].find((p) => existsSync(join(root, p))) ?? null;
};
const rows = routes.map((r) => {
  if (r.route.startsWith('https://')) return { ...r, status: 'web (NANO-11 host)', file: null };
  if (r.route.startsWith('(')) return { ...r, status: 'dialog component', file: null };
  const file = fileFor(r.route);
  if (file) return { ...r, status: r.bookingMode === 'inapp' ? 'gated (D33): unreachable in hand-off' : 'built', file };
  return { ...r, status: r.bookingMode === 'inapp' ? 'gated (D33, no provider)' : 'MISSING', file: null };
});
const missing = rows.filter((r) => r.status === 'MISSING');

// ---------- report ----------
const out = [];
out.push('# Coverage audit', '', `Generated by \`node scripts/audit-coverage.mjs\`. Requirements: ${ids.length} IDs, ${ids.length - untraced.length} traced. Routes: ${rows.length}, ${missing.length} missing.`, '');
out.push('## Untraced requirement IDs', '');
out.push(untraced.length ? untraced.map((id) => `- ${id} (${priority[id] ?? '?'})`).join('\n') : 'None.', '');
out.push('## Routes', '', '| Route | Screens | Mode | Status | File |', '|---|---|---|---|---|');
for (const r of rows) out.push(`| \`${r.route}\` | ${r.screens} | ${r.bookingMode} | ${r.status} | ${r.file ? `\`${r.file.replace(/\\/g, '/')}\`` : '—'} |`);
// --check: one summary line (CI); default: the full Markdown report.
console.log(process.argv.includes('--check') ? out[2] : out.join('\n'));
process.exitCode = untraced.length || missing.length ? 1 : 0;
